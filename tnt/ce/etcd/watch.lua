--- Наблюдение источника etcd за конфигурацией в хранилище.
---
--- Узел, не заметивший правку, остаётся на прежней конфигурации навсегда,
--- а поднятый на снимке — на снимке. Наблюдатель раз в такт спрашивает
--- хранилище, что прочитало бы сейчас чтение конфигурации, и, если это
--- разошлось с тем, на чём живёт узел, просит ядро перечитать её.
---
--- Модуль — часть источника, а не отдельный класс: он работает над
--- состоянием источника (`tnt.ce.etcd.source`) — что прочитано, откуда
--- и как ходить в хранилище, — и сам ничего не хранит. Отдельным файлом
--- он потому, что чтение конфигурации и наблюдение за ней — две работы,
--- и у каждой свой обход.
---
--- Контекст. Наблюдатель порождается без `context.bind` и контекста того,
--- кто его завёл, не несёт: иначе все его заходы до перезапуска узла
--- писались бы под опознавателем давно закончившегося перечитывания.
--- Зато каждый заход идёт в своей области (`tnt-context`) с новым
--- `request_id`: записи захода, перечитывание, которое он попросил,
--- и записи ролей, которые это перечитывание применило, связаны одним
--- опознавателем, а соседние заходы — нет.

local context = require('tnt.context')
local id = require('tnt.id')

local Module = {}

---@class TntEtcdPollAnswer
---@field key string Ключ, с которого sync прочитал бы конфигурацию сейчас
---@field revision number|nil Ревизия этого ключа

--- Спрашивает у хранилища, с какого ключа sync прочитал бы конфигурацию
--- сейчас и какова ревизия этого ключа.
---
--- Ключи спрашиваются в том же порядке, в каком их читает sync: основной,
--- а если его нет — старый. Так наблюдение видит и правку старого ключа,
--- на котором живёт развёртывание, и основной ключ, записанный при
--- переезде поверх старого, — ровно то, что прочитало бы перечитывание.
---
--- Сравнивается ревизия ключа, а не хранилища: ту двигают и назначение
--- лидера, и замок, и узел перечитывал бы конфигурацию на каждую такую
--- запись.
---@param source TntEtcdSource
---@return TntEtcdPollAnswer|nil answer nil — ни одного ключа нет либо хранилище молчит
---@return string|nil err Почему хранилище не ответило
local function poll(source)
    local request = source._watch_request

    -- До первого чтения адресов нет, и спрашивать некого.
    if request == nil then
        return nil
    end

    for _, key in ipairs({ request.primary_key, request.legacy_key }) do
        local body, err, meta = request.client:fetch(request.endpoints, key, request.options)

        -- Без сведений об ответе — хранилище не ответило; ключа нет —
        -- ответило, и спрашивается следующий.
        if meta == nil then
            return nil, err
        end

        if body ~= nil then
            return { key = key, revision = tonumber(meta.mod_revision) }
        end
    end

    return nil
end

--- Разошёлся ли ключ, который прочитал бы sync, с конфигурацией узла.
---
--- Узлу на снимке или без ключа сравнивать ревизию не с чем, и для него
--- изменение — сам ключ, который теперь читается: etcd вернулся либо
--- конфигурацию записали впервые. Сменившийся ключ — тоже изменение:
--- основной записали поверх старого.
---@param source TntEtcdSource
---@param answer TntEtcdPollAnswer
---@return boolean
local function changed(source, answer)
    if answer.key ~= source._key then
        return true
    end

    -- Ревизии нет — сравнивать нечего: перечитывание принесло бы ту же
    -- безымянную конфигурацию и повторялось бы каждый такт.
    return answer.revision ~= nil and source._revision ~= nil and answer.revision > source._revision
end

--- Один такт наблюдения: спросить хранилище и, если конфигурация
--- изменилась, попросить ядро перечитать её.
---
--- Заметив изменение, источник не применяет его сам: он просит ядро
--- перечитать конфигурацию, а то в свою очередь снова позовёт sync. Иначе
--- получилось бы два места, которые решают, какая конфигурация действует.
---@param source TntEtcdSource
---@return string|nil failure Почему попытка не удалась; nil — хранилище ответило
local function tick(source)
    local asked, answer, err = pcall(poll, source)

    if not asked then
        -- Обращение к хранилищу сорвалось исключением: наблюдатель
        -- обязан пережить это и сказать вслух.
        source._log.warn('наблюдение за конфигурацией сорвалось', { err = answer })

        return tostring(answer)
    end

    if err ~= nil then
        -- Молчащее хранилище изменением не считается: узел продолжает
        -- жить на том, что у него есть, а о беде расскажет следующий sync.
        return err
    end

    -- Пропавший ключ изменением не считается: перечитывание дало бы узлу
    -- пустую конфигурацию вместо рабочей, и он живёт на той, что есть, —
    -- как при молчании хранилища.
    if answer ~= nil and changed(source, answer) then
        source._log.info('конфигурация в хранилище изменилась, перечитываю')

        local reloaded, reload_error = pcall(source._reload)

        if not reloaded then
            -- Перечитывание валится, например, когда узел вычеркнут
            -- из новой конфигурации. Наблюдателя это не убивает:
            -- следующая правка может его вернуть.
            source._log.warn('конфигурация не перечитана', { err = reload_error })
        end
    end

    return nil
end

--- Один заход наблюдателя: такт и счёт неудач подряд.
---
--- Зовётся внутри области захода, поэтому и отказ, остановивший
--- наблюдение, пишется под опознавателем того захода, что стал последним.
---@param source TntEtcdSource
---@param failures integer Сколько попыток подряд хранилище не ответило до захода
---@return integer failures Сколько их после захода
local function round(source, failures)
    local failure = tick(source)

    if failure == nil then
        return 0
    end

    failures = failures + 1

    local limit = source._watchers.reconnect_max_attempts
    if limit ~= nil and failures >= limit then
        source._log.error(
            'наблюдение за конфигурацией остановлено: хранилище не отвечает',
            { attempts = failures, err = failure }
        )
        source._watching = false
    end

    return failures
end

--- Начинает следить за ключом конфигурации источника.
---
--- Наблюдение опросом, хотя поток через HTTP-шлюз etcd есть
--- (`/v3/watch`). Источнику поток ничего не дал бы. Раскатка
--- конфигурации и так просит узлы перечитать её сразу после записи,
--- а мимо раскатки конфигурацию правят руками, и несколько секунд
--- задержки там ничего не стоят — в отличие от узла, который не заметил
--- правку вовсе и остался на прежней конфигурации навсегда. Опрос
--- не отменил бы и поток: он ускоритель, а не замена, и правку,
--- записанную, пока поток переподключается, ловит только опрос.
---
--- Молчание хранилища наблюдение переживает по настройкам
--- config.etcd.watchers: после неудачной попытки ждёт
--- `reconnect_timeout` (без него — обычный такт), а после
--- `reconnect_max_attempts` неудач подряд останавливается и говорит об
--- этом; без предела попытки не кончаются. Предел действует и на узле,
--- поднятом на снимке: оператор, поставивший его, выбрал остановку
--- громкой ошибкой вместо опроса без конца. Остановленное наблюдение
--- заводит заново следующий sync, не кончившийся отказом, — то есть
--- перечитывание конфигурации.
---@param source TntEtcdSource
function Module.start(source)
    if source._watching or not source._watch_enabled then
        return
    end

    source._watching = true

    source._spawn(function()
        -- Сколько попыток подряд хранилище не ответило: от этого зависит
        -- и пауза перед следующей, и решение остановиться.
        local failures = 0

        while source._watching do
            source._sleep(failures > 0 and source._watchers.reconnect_timeout or source._watch_interval)

            -- Признак читается заново после ожидания: наблюдение
            -- останавливают снаружи, и проснувшийся наблюдатель обязан
            -- это заметить, а не сделать ещё один заход.
            ---@type any
            local alive = source._watching

            if not alive then
                break
            end

            -- Опознаватель — новый на каждый заход: заход и есть одна
            -- операция наблюдателя.
            failures = context.run({ [context.REQUEST_ID] = id.ulid() }, round, source, failures)
        end
    end)
end

return Module
