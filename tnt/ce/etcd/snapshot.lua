--- Локальный снимок конфигурации кластера.
---
--- etcd, объявленный источником конфигурации, становится обязательным для
--- старта: без него инстанс не поднимется. Для шардированного кластера это
--- значит, что авария etcd блокирует рестарт — снимок снимает эту связку.
---
--- После каждого успешного чтения конфигурация кладётся рядом с данными
--- инстанса. Если etcd недоступен, инстанс поднимается на снимке и честно
--- сообщает, что конфигурация устарела.
---
--- Путь снимка и выключатель отката приходят окружением и читаются через
--- `tnt-env`: переменная из `.env` действует и на узле, поднятом не через
--- `make`, а значение выключателя приводится тем же правилом, что и всякое
--- логическое из окружения. И `.env`, и относительный путь снимка
--- считаются от рабочего каталога узла — `process.work_dir`, — по обе
--- стороны `box.cfg` одинаково (см. `directory`).
---
--- Файл снимка читается, подменяется и опрашивается через `tnt-fs`, и там же
--- проверки подменяют `fio` (`fs._set_source`): отказ записи на настоящем
--- диске воспроизводится ненадёжно и зависит от прав пользователя.

local fio = require('fio')

local env = require('tnt.env')
local external = require('tnt.external')
local fs = require('tnt.fs')

local Module = {}

--- Что снимок, кроме файлов, узнаёт у мира: настроен ли уже `box`.
---
--- Внешней зависимостью, а не прямым `type(box.cfg)`: в процессе проверок `box.cfg`
--- не зовут, и ветку «первый `box.cfg` позади» иначе проверить нечем.
local source = external.install(Module, {
    configured = function()
        return type(box.cfg) ~= 'function'
    end,
})

--- Путь к снимку по умолчанию, относительно рабочего каталога инстанса.
local DEFAULT_PATH = 'var/etcd-config-snapshot.yaml'

--- Права файла снимка: 0644 за вычетом umask процесса, а закрывают снимок
--- правами его каталога. Явно: без них подмена взяла бы права старого
--- файла, а новому дала бы 0640, и права снимка зависели бы от того, чем
--- его подменили в прошлый раз. Десятичным, потому что восьмеричной записи
--- в Lua нет.
local FILE_MODE = 420

--- Переменные окружения: путь снимка и выключатель отката.
local ENV_PATH = 'TNT_CE_ETCD_SNAPSHOT'
local ENV_FALLBACK = 'TNT_CE_ETCD_FALLBACK'

--- Отказ каталога с подстановкой, которой до `box.cfg` не раскрыть.
local UNRESOLVED = 'process.work_dir «%s»: до box.cfg раскрывается только {{ instance_name }}'

--- Каталог узла, от которого считаются `.env` и относительный путь снимка.
---
--- Правило ядра для файлов, которые оно само читает при сборе
--- конфигурации (`config.context … from: file`): относительный путь
--- считается от `process.work_dir`. Первый `box.cfg` переходит в этот
--- каталог, и после него путь считается от текущего, а до него каталог
--- приписывается руками. Источник же читают по обе стороны `box.cfg`:
--- на старте, ещё раз сразу после `box.cfg`, если подъём мог быть долгим
--- (у узла с данными — на всяком перезапуске), и на каждом
--- `config:reload()`. Без этого правила узел на 3.8 брал выключатель
--- отката и снимок из `.env` каталога запуска в первом чтении и из `.env`
--- рабочего каталога во всех следующих: выключатель, сказанный только
--- рабочему каталогу, пропускал первый старт и ронял перезапуск
--- (опыт на узле держит живая проверка `work_dir_live_test.lua`).
---
--- Каталог берётся из того, что собрали источники до etcd, — окружения
--- (`TT_PROCESS_WORK_DIR`) и файла. Каталог, названный только в самом
--- etcd, до его чтения неизвестен, и до `box.cfg` пути считаются от
--- каталога запуска.
---
--- Из подстановок раскрывается одна — `{{ instance_name }}`: имя инстанса
--- ядро знает с запуска. Имена репликасета и группы — из топологии,
--- которой до чтения etcd может не быть вовсе, а контекст ядро раскрывает
--- позже. Каталог с ними не определить, и это отказ парой: чей `.env`
--- читать вместо, решает источник.
---@param iconfig table|nil Конфигурация инстанса, собранная источниками до etcd
---@param instance_name string|nil Имя инстанса
---@return string|nil directory Каталог узла; nil — текущий каталог процесса
---@return string|nil err Почему каталог не определить
function Module.directory(iconfig, instance_name)
    if source().configured() then
        return nil
    end

    local process = type(iconfig) == 'table' and iconfig.process or nil
    local work_dir = type(process) == 'table' and process.work_dir or nil

    -- Пустота от YAML (`box.NULL`) — тоже «не задан»: строкой её не сделать.
    if type(work_dir) ~= 'string' then
        return nil
    end

    local resolved = work_dir:gsub('{{ *instance_name *}}', function()
        return instance_name
    end)

    -- Фигурная скобка в образцах Lua не особый знак: поиск без начала
    -- и без «буквально» ищет ровно две скобки, а мутанта начала `0`,
    -- неотличимого от `1`, у него нет.
    if resolved:find('{{') then
        return nil, UNRESOLVED:format(work_dir)
    end

    return resolved
end

--- Путь, отсчитанный от каталога узла.
---
--- Абсолютный путь остаётся собой. Относительный приписывается к каталогу
--- и сразу нормализуется, как это делает ядро: рабочий каталог создаётся
--- позже, при применении конфигурации, и путь `work/../снимок` через
--- ещё не созданный каталог не нашёлся бы на диске.
---@param directory string|nil
---@param path string
---@return string
local function within(directory, path)
    if directory == nil or path:startswith('/') then
        return path
    end

    return fio.abspath(fio.pathjoin(directory, path))
end

--- Что сказано снимку окружением.
---@class TntCeEtcdSnapshotSettings
---@field path string Путь к снимку
---@field fallback boolean Разрешён ли откат на снимок

--- Читает окружение узла: путь снимка и выключатель отката.
---
--- Чтение своё, а не общее на процесс: источник зовут раньше
--- приложения, до `box.cfg`, и общее чтение, заведённое здесь, закрепило
--- бы за приложением `.env` каталога запуска.
---
--- Одно чтение `.env` — на одно чтение конфигурации, а не на каждый
--- вопрос: путь, по которому снимок ищут, пишут и называют в журнале,
--- и выключатель берутся из одного прочтения и разойтись не могут, даже
--- если файл правят в эту самую секунду. Правка `.env` действует со
--- следующего чтения конфигурации — с ближайшего `config:reload()`.
---
--- Пустая переменная пути — не путь, а то же, что незаданная: снимок без
--- имени файла записать некуда, а пустоту в переменной оставляют, когда
--- хотят умолчания.
---
--- Откат разрешён по умолчанию. Кластеру, где расхождение конфигурации
--- опаснее простоя, он не нужен: выключается значением off, false, 0 или
--- no. Прочее, что не значит ни да, ни нет, — отказ, а не молча
--- включённый откат: опечатку в выключателе оператор иначе обнаружил бы
--- в тот день, когда etcd лёг, а узел поднялся на снимке вопреки его
--- решению.
---
--- Пустой выключатель — тоже «прочее», хотя пустой путь — умолчание
--- (решение владельца 16.09.2026). Умолчание пути ничем не грозит:
--- снимок ляжет на своё обычное место. Пустой выключатель — решение,
--- которое оператор начал записывать и не записал, и откат, включённый
--- за него, — та самая ошибка, от которой бережёт отказ.
--- До перехода на `tnt-env` пустота включала откат, и узел со строкой
--- `TNT_CE_ETCD_FALLBACK=` после обновления не стартует.
---@param directory string|nil Каталог узла (`directory`); nil — текущий
---@return TntCeEtcdSnapshotSettings
function Module.settings(directory)
    local reader = env.new({ path = within(directory, env.DEFAULT_PATH) })
    local path = reader:string(ENV_PATH)

    if path == nil or path == '' then
        path = DEFAULT_PATH
    end

    return {
        path = within(directory, path),
        fallback = reader:bool(ENV_FALLBACK, true) == true,
    }
end

--- Сохраняет конфигурацию. Отказ записи не должен ронять инстанс: снимок —
--- подстраховка, а не источник правды, и потеря записи не мешает работе.
---
--- Подменой `fs.replace`: временный файл рядом с целью со случайной частью
--- имени, сброс на диск, переименование поверх снимка и сброс каталога.
--- Обрыв посреди записи не оставит обрезанного снимка, отключение
--- питания — пустого, на котором инстанс потом не поднимется, а два
--- сохранения разом не пишут в один временный файл. Рядом с целью, а не
--- в `/tmp`: переименование атомарно только в пределах одной файловой
--- системы.
---
--- Что не удалось, снимок называет своим текстом, а у отказа `tnt-fs`
--- берёт только причину (`reason`): текст отказа целиком назвал бы путь
--- дважды.
---@param body string Тело конфигурации в том виде, в каком его отдал etcd
---@param path string Путь к снимку (`settings`)
---@return boolean saved
---@return string|nil err
function Module.save(body, path)
    -- Для имени без каталога dirname отдаёт точку, а не пустую строку,
    -- и заводить нечего: каталог, который уже есть, — тоже удача.
    local directory = fio.dirname(path)
    local made, make_err = fs.make_tree(directory)

    if not made then
        ---@cast make_err TntFsFailure
        return false, ('не удалось создать каталог %s: %s'):format(directory, make_err.reason)
    end

    local replaced, err = fs.replace(path, body, { mode = FILE_MODE })

    if not replaced then
        ---@cast err TntFsFailure
        return false, ('не удалось записать %s: %s'):format(path, err.reason)
    end

    return true, nil
end

--- Читает сохранённую конфигурацию.
---@param path string Путь к снимку (`settings`)
---@return string|nil body
---@return string|nil err
function Module.load(path)
    local body, err = fs.read(path)

    if body == nil then
        ---@cast err TntFsFailure
        if err.kind == fs.MISSING then
            return nil, ('снимок %s не найден'):format(path)
        end

        return nil, ('не удалось прочитать %s: %s'):format(path, err.reason)
    end

    if body == '' then
        return nil, ('снимок %s пуст'):format(path)
    end

    return body, nil
end

--- Время последнего изменения снимка, целыми секундами.
---
--- Снимка нет либо его не опросить — ответ пустота, а не ноль: ноль
--- читался бы как 1970 год, и возраст снимка в докладе вышел бы в полвека.
---@param path string Путь к снимку (`settings`)
---@return number|nil
function Module.saved_at(path)
    local info = fs.stat(path)

    if info == nil then
        return nil
    end

    return info.mtime
end

return Module
